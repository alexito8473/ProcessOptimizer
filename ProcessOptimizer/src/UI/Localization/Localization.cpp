    const char* Translate(Language language, Text text)
    {
        const std::size_t index =
            static_cast<std::size_t>(text);

        if (index >= Count)
            return "";

        return language == Language::Spanish
            ? SpanishTexts[index]
            : EnglishTexts[index];
    }

    const char* LanguageName(Language language)
    {
        return Translate(
            language,
            language == Language::Spanish
                ? Text::Spanish
                : Text::English);
    }
